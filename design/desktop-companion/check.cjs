const {chromium}=require('playwright'),fs=require('node:fs'),path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.SPECTRUMDECK_BROWSER_PATH});
 const page=await browser.newPage({viewport:{width:1440,height:1080}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(fs.readFileSync(process.env.SPECTRUMDECK_TEST_URL_FILE,'utf8').trim());
 await page.getByRole('button',{name:'Browse for card'}).click();
 await page.getByText('No SpectrumDeck library yet.',{exact:false}).waitFor();
 await page.getByRole('button',{name:'Choose game folder'}).click();
 await page.getByRole('button',{name:'Preview pack',exact:true}).click();
 await page.getByRole('heading',{name:'02 / Review your releases'}).waitFor();
 if(!await page.getByRole('button',{name:/Add .* releases/}).isDisabled())throw Error('Unresolved format enabled import');
 await page.getByRole('button',{name:'Review Night Relay',exact:true}).click();
 await page.locator('#choice').selectOption('Night Relay.tap');
 await page.evaluate(()=>document.fonts.ready);
 await page.screenshot({path:path.join(__dirname,'review-preview.png'),fullPage:true});
 await page.locator('#search').fill('Paper');
 if(await page.locator('.release').count()!==1)throw Error('Search did not filter');
 await page.locator('#search').fill('');
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 await page.screenshot({path:path.join(__dirname,'mobile-preview.png'),fullPage:true});
 await page.setViewportSize({width:1440,height:1080});
 await page.getByRole('button',{name:'Add 3 releases',exact:true}).click();
 await page.getByRole('heading',{name:'Your library has room for more.'}).waitFor();
 await page.screenshot({path:path.join(__dirname,'complete-preview.png'),fullPage:true});
 const pending=page.waitForEvent('download');await page.getByRole('button',{name:'Save import report'}).click();
 const report=JSON.parse(fs.readFileSync(await (await pending).path(),'utf8'));
 if(report.generation!==1||report.report.included.length!==3)throw Error('Real import report incorrect');
 await page.getByRole('button',{name:'Import another pack'}).click();
 await page.getByRole('button',{name:'Refresh cards'}).click();
 await page.getByRole('button',{name:'Preview pack',exact:true}).click();
 await page.getByRole('heading',{name:'02 / Review your releases'}).waitFor();
 if(!await page.getByRole('button',{name:'Add 0 releases',exact:true}).isDisabled())throw Error('Duplicate-only pack enabled import');
 await page.reload();await page.getByRole('button',{name:'Browse for card'}).waitFor();
 if(await page.locator('#notice').textContent())throw Error('Session token did not survive reload');
 if(errors.length)throw Error(errors.join('\n'));
 fs.writeFileSync(path.join(__dirname,'checks.json'),JSON.stringify({checks:['Empty-card guidance','Native picker adapter','Actual pack preview','Format guard','Format choice','Release search','390px reflow','Actual verified import','Report download','Duplicate-only guard','Session reload'],errors},null,2)+'\n');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
